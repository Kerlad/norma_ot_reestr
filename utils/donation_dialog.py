def _donation_state_path() -> str:
    return os.path.join(get_app_data_dir(), DONATION_STATE_FILE)


def _load_donation_state() -> dict:
    path = _donation_state_path()
    if os.path.exists(path):
        try:
            with open(path, 'r', encoding='utf-8') as f:
                return json.load(f)
        except (json.JSONDecodeError, OSError) as e:
            logger.debug(f"Failed to load donation state: {e}")
    return {"last_shown": None, "disabled": False}


def _save_donation_state(state: dict) -> None:
    path = _donation_state_path()
    try:
        with open(path, 'w', encoding='utf-8') as f:
            json.dump(state, f, ensure_ascii=False, indent=2)
    except OSError as e:
        logger.warning(f"Failed to save donation state: {e}")


def should_show_donation() -> bool:
    state = _load_donation_state()
    if state.get("disabled", False):
        return False
    last_shown = state.get("last_shown")
    if last_shown is None:
        return True
    try:
        last = datetime.fromisoformat(last_shown)
        return (datetime.now() - last).days >= DONATION_COOLDOWN_DAYS
    except (ValueError, TypeError):
        return True


def _mark_donation_shown() -> None:
    state = _load_donation_state()
    state["last_shown"] = datetime.now().isoformat()
    _save_donation_state(state)


def _disable_donation_forever() -> None:
    _save_donation_state({"last_shown": datetime.now().isoformat(), "disabled": True})


def show_donation_if_needed(parent=None) -> bool:
    if should_show_donation():
        dialog = DonationDialog(parent)
        result = dialog.exec()
        if result == DonationDialog.Accepted:
            _mark_donation_shown()
            return True
        elif result == DonationDialog.Disabled:
            _disable_donation_forever()
            return False
    return False


