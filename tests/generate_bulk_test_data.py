def random_snils():
    d = [random.randint(0, 9) for _ in range(11)]
    return ''.join(str(x) for x in d)

def random_date(days_back_start=365, days_back_end=1):
    d = datetime.now() - timedelta(days=random.randint(days_back_end, days_back_start))
    return d.strftime("%d.%m.%Y")

def make_programs():
    r = random.random()
    if r < 0.3:
        return random.choice(COMMON_PROGRAMS)
    elif r < 0.55:
        return ','.join(random.sample(COMMON_PROGRAMS, random.randint(2, 4)))
    else:
        p = [random.choice(COMMON_PROGRAMS)]
        p.append(random.choice([x for x in VALID_PROGRAMS if x not in COMMON_PROGRAMS]))
        return ','.join(p)

